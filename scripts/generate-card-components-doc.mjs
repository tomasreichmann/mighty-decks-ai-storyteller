import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  actorBaseLayerCatalog,
  actorTacticalRoleCatalog,
  actorTacticalSpecialCatalog,
  assetBaseCatalog,
  assetModifierCatalog,
  counterIconCatalog,
  rulesEffectCards,
  rulesOutcomeCards,
  rulesStuntCards,
} from "../spec/dist/index.js";

const scriptPath = fileURLToPath(import.meta.url);
const repositoryRoot = resolve(dirname(scriptPath), "..");
const defaultOutputPath = resolve(
  repositoryRoot,
  "docs",
  "mighty-decks-card-components.md",
);

const escapeCell = (value) =>
  String(value ?? "")
    .replaceAll("|", "\\|")
    .replace(/\r?\n/g, "<br>");

const table = (headers, rows) => [
  `| ${headers.join(" | ")} |`,
  `| ${headers.map(() => "---").join(" | ")} |`,
  ...rows.map((row) => `| ${row.map(escapeCell).join(" | ")} |`),
  "",
];

const section = (title, entries, headers, rowForEntry) => [
  `## ${title} (${entries.length})`,
  "",
  ...table(headers, entries.map(rowForEntry)),
];

export const renderCardComponentsMarkdown = () =>
  [
    "# Mighty Decks Card Components",
    "",
    "> Generated by `pnpm docs:cards`. Do not edit this file manually.",
    "",
    "This standalone reference lists every card and composable card layer exported by the shared catalogs in `spec/`.",
    "",
    ...section(
      "Outcome Cards",
      rulesOutcomeCards,
      ["Title", "Slug", "Description", "Instructions", "Count", "Deck", "Shortcode"],
      (card) => [
        card.title,
        card.slug,
        card.description,
        card.instructions,
        card.count,
        card.deck,
        card.code,
      ],
    ),
    ...section(
      "Effect Cards",
      rulesEffectCards,
      ["Title", "Slug", "Effect", "Additional text", "Count", "Deck", "Shortcode"],
      (card) => [
        card.title,
        card.slug,
        card.nounEffect,
        card.adjectiveEffect,
        card.count,
        card.deck,
        card.code,
      ],
    ),
    ...section(
      "Stunt Cards",
      rulesStuntCards,
      ["Title", "Slug", "Requirement", "Effect", "Count", "Deck", "Shortcode"],
      (card) => [
        card.title,
        card.slug,
        card.requirements,
        card.effect,
        card.count,
        card.deck,
        card.code,
      ],
    ),
    ...section(
      "Actor Base Layers",
      actorBaseLayerCatalog,
      ["Label", "Slug"],
      (entry) => [entry.label, entry.slug],
    ),
    ...section(
      "Actor Tactical Roles",
      actorTacticalRoleCatalog,
      ["Label", "Slug"],
      (entry) => [entry.label, entry.slug],
    ),
    ...section(
      "Actor Tactical Specials",
      actorTacticalSpecialCatalog,
      ["Label", "Slug"],
      (entry) => [entry.label, entry.slug],
    ),
    ...section(
      "Asset Bases",
      assetBaseCatalog,
      ["Title", "Slug", "Group"],
      (entry) => [entry.title, entry.slug, entry.group],
    ),
    ...section(
      "Asset Modifiers",
      assetModifierCatalog,
      ["Title", "Slug"],
      (entry) => [entry.title, entry.slug],
    ),
    ...section(
      "Counter Icons",
      counterIconCatalog,
      ["Label", "Slug"],
      (entry) => [entry.label, entry.slug],
    ),
  ].join("\n");

const parseOutputPath = (arguments_) => {
  const outputFlagIndex = arguments_.indexOf("--output");
  if (outputFlagIndex === -1) {
    return defaultOutputPath;
  }

  const requestedPath = arguments_[outputFlagIndex + 1];
  if (!requestedPath) {
    throw new Error("--output requires a file path");
  }

  return resolve(repositoryRoot, requestedPath);
};

const isMain = process.argv[1] && resolve(process.argv[1]) === scriptPath;

if (isMain) {
  const outputPath = parseOutputPath(process.argv.slice(2));
  writeFileSync(outputPath, renderCardComponentsMarkdown(), "utf8");
  process.stdout.write(`Generated ${outputPath}\n`);
}
